/* Generates asset-manifest.json at the project root from REAL on-disk files.
   No sizes are guessed — every byte count is stat()'d. URLs carry no query
   strings in this project, so url === urlWithQuery for every entry.
   stage: "shell"      -> Stage A: preloaded BEFORE the Start button is revealed
          "background" -> Stage B: warmed during idle time after window load
   warmVia: "fetch"  -> the parent preloader fetches it
            "iframe" -> warmed inside the hidden game iframe (its own boot
                        preloaders + embed-bridge.js); the parent must NOT fetch
                        it too, or every game asset would download twice. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

function entry(rel, opts) {
  const abs = path.join(ROOT, rel);
  const bytes = fs.statSync(abs).size;
  const url = rel.split(path.sep).join("/").split("/").map(encodeURIComponent).join("/");
  return {
    url,
    urlWithQuery: url, // no cache-busting query strings are used in this project
    type: opts.type,
    bytes,
    stage: opts.stage,
    usage: opts.usage || "",
    target: opts.target || null,
    blobAllowed: !!opts.blobAllowed,
    game: !!opts.game,
    warmVia: opts.warmVia || "fetch",
    order: opts.order ?? 100,
  };
}

const entries = [];

/* ---------- Stage A: the flipbook shell (gates the Start button) ---------- */
entries.push(entry("assets/cover-page.webp", { type: "image", stage: "shell", usage: "cover artwork (CSS background)", order: 1 }));
entries.push(entry("assets/play-button.webp", { type: "image", stage: "shell", usage: "Start button artwork", target: "#hint img", blobAllowed: true, order: 2 }));
for (let i = 1; i <= 4; i++) {
  entries.push(entry(`assets/posters/${i}.webp`, { type: "image", stage: "shell", usage: `page video poster ${i}`, order: 3 }));
}
entries.push(entry("game/assets/GameStartScreen.webp", { type: "image", stage: "shell", usage: "LBD page poster (leaf + overlay backdrop)", game: true, order: 4 }));

/* ---------- Stage B: later pages + shared audio (parent-fetched) ---------- */
["1", "2", "3", "4"].forEach((n, i) =>
  entries.push(entry(`assets/${n}.webm`, { type: "video", stage: "background", usage: `story page ${n} video`, order: 10 + i }))
);
entries.push(entry("game/audios/ThemeMusic.ogg", { type: "audio", stage: "background", usage: "background music (shared with the game)", game: true, order: 20 }));
entries.push(entry("sfx/Page flip.mp3", { type: "audio", stage: "background", usage: "page-flip SFX fallback (Web Audio path uses inlined base64)", order: 30 }));
entries.push(entry("sfx/cover page flip.mp3", { type: "audio", stage: "background", usage: "cover-flip SFX fallback", order: 31 }));

/* ---------- Stage B: embedded game (warmed inside the hidden iframe) ------ */
entries.push(entry("game/index.html", { type: "document", stage: "background", usage: "embedded LBD (loads in the hidden iframe during idle)", game: true, warmVia: "iframe", order: 40 }));
entries.push(entry("game/embed-bridge.js", { type: "script", stage: "background", usage: "LBD embed bridge", game: true, warmVia: "iframe", order: 41 }));
for (const dir of ["game/assets", "game/audios"]) {
  for (const name of fs.readdirSync(path.join(ROOT, dir)).sort()) {
    if (dir === "game/assets" && name === "GameStartScreen.webp") continue; // already a shell entry
    const rel = `${dir}/${name}`;
    const type = /\.(webm|mp4)$/i.test(name) ? "video" : /\.ogg$/i.test(name) ? "audio" : "image";
    entries.push(
      entry(rel, {
        type,
        stage: "background",
        usage: dir === "game/audios" ? "game audio (warmed by embed-bridge idle warmer)" : "game sprite (warmed by the game's own boot preloaders)",
        game: true,
        warmVia: "iframe",
        order: 50,
      })
    );
  }
}

const manifest = {
  generated: new Date().toISOString(),
  note: "Generated by dev/gen-manifest.mjs from real on-disk files — do not edit by hand.",
  totalBytes: entries.reduce((a, e) => a + e.bytes, 0),
  shellBytes: entries.filter((e) => e.stage === "shell").reduce((a, e) => a + e.bytes, 0),
  entries,
};
fs.writeFileSync(path.join(ROOT, "asset-manifest.json"), JSON.stringify(manifest, null, 2));
console.log(
  `asset-manifest.json: ${entries.length} entries, shell ${(manifest.shellBytes / 1024).toFixed(0)}KB, total ${(manifest.totalBytes / 1048576).toFixed(1)}MB`
);
